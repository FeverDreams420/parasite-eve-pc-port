#!/usr/bin/env python3
"""Collect absolute addresses for every data symbol the game uses.

Sources, all from the repository (no game data):
  * linkers/USA/undefined_syms_auto.main.txt, undefined_syms_manual.txt,
    undefined_funcs_auto.main.txt  (NAME = 0xADDR;)
  * labels in the split data/rodata assembly, placed with configs/USA/main.yaml
    (their PS1 objects are checked against the retail bytes).
Writes a GNU ld script of assignments (host link input) and a JSON map.
Usage: gen_abs_syms.py OUT.ld [--json OUT.json]
"""
import json, pathlib, re, subprocess, sys
import yaml

READELF = 'mipsel-none-elf-readelf'
EXE = pathlib.Path('assets/USA/main.exe').read_bytes()


def sh(*a):
    return subprocess.run(a, check=True, capture_output=True, text=True).stdout


def txt_syms():
    out = {}
    for f in ['linkers/USA/undefined_syms_auto.main.txt', 'linkers/USA/undefined_syms_manual.txt',
              'linkers/USA/undefined_funcs_auto.main.txt']:
        for m in re.finditer(r'^\s*([A-Za-z_.$][\w.$]*)\s*=\s*(0x[0-9A-Fa-f]+)\s*;', pathlib.Path(f).read_text(), re.M):
            out.setdefault(m.group(1), (int(m.group(2), 16), f))
    return out


def obj_syms(obj, base_by_sec):
    syms = {}
    for line in sh(READELF, '-sW', str(obj)).splitlines():
        p = line.split()
        if len(p) >= 8 and p[6].isdigit() and int(p[6]) in base_by_sec and p[3] in ('OBJECT', 'NOTYPE'):
            if p[4] in ('GLOBAL', 'WEAK') or p[4] == 'LOCAL' and not p[7].startswith('.'):
                syms[p[7]] = base_by_sec[int(p[6])] + int(p[1], 16)
    return syms


def main():
    out_ld = pathlib.Path(sys.argv[1])
    cfg = yaml.safe_load(open('configs/USA/main.yaml'))
    seg = next(s for s in cfg['segments'] if isinstance(s, dict) and s.get('name') == 'main')
    fs, vram = seg['start'], seg['vram']
    syms = {k: v[0] for k, v in txt_syms().items()}
    src = {k: 'linker txt' for k in syms}
    asm_checked = 0
    for sub in seg['subsegments']:
        if isinstance(sub, dict):
            off, kind, name = sub.get('start'), sub.get('type'), sub.get('name')
        elif len(sub) >= 3:
            off, kind, name = sub[0], sub[1], sub[2]
        else:
            continue
        if kind not in ('data', 'rodata'):
            continue
        obj = pathlib.Path('build/USA/asm/USA/main/data/%s.%s.s.o' % (name, kind))
        if not obj.exists():
            raise SystemExit('missing object ' + str(obj))
        secname = '.' + kind
        base = {}
        for line in sh(READELF, '-SW', str(obj)).splitlines():
            m = re.match(r'\s*\[\s*(\d+)\]\s+(\S+)\s+\S+\s+[0-9a-f]+\s+([0-9a-f]+)\s+([0-9a-f]+)', line)
            if m and m.group(2) == secname:
                base[int(m.group(1))] = vram + off - fs
                size = int(m.group(4), 16)
                fo = off
                body = obj.read_bytes()[int(m.group(3), 16):int(m.group(3), 16) + size]
                # Words holding relocations (pointers) are zero in the object.
                rel = set()
                for rl in sh(READELF, '-rW', str(obj)).splitlines():
                    mm = re.match(r'\s*([0-9a-f]{8})\s+[0-9a-f]{8}\s+R_MIPS_', rl)
                    if mm:
                        rel.add(int(mm.group(1), 16) & ~3)
                for w in range(0, size - size % 4, 4):
                    if w not in rel and body[w:w + 4] != EXE[fo + w:fo + w + 4]:
                        raise SystemExit('%s differs from retail at +0x%X' % (obj, w))
                asm_checked += 1
        for k, a in obj_syms(obj, base).items():
            if k in syms and syms[k] != a:
                raise SystemExit('address conflict for %s: 0x%X vs 0x%X' % (k, syms[k], a))
            syms[k] = a
            src.setdefault(k, str(obj))
    # Scratchpad aliases used through asm labels (asm("0x1F800008")).
    for a in range(0x1F800000, 0x1F800400, 1):
        pass
    lines = ['/* Generated by tools/pc/gen_abs_syms.py. */']
    for k in sorted(syms):
        lines.append('%s = 0x%08X;' % (k, syms[k]))
    out_ld.write_text('\n'.join(lines) + '\n')
    if '--json' in sys.argv:
        pathlib.Path(sys.argv[sys.argv.index('--json') + 1]).write_text(json.dumps(syms, indent=0))
    print(json.dumps({'symbols': len(syms), 'asm_sections_checked': asm_checked}))


if __name__ == '__main__':
    main()
